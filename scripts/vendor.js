// Usage: npm run vendor
// Copies third-party browser assets from node_modules into public/vendor/, so the deployed
// app serves them from its own origin (no CDN) and deploys do not depend on node_modules.
// The copies are committed; rerun this only after changing a pinned version in package.json.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const assets = [{ pkg: 'bootstrap', from: 'dist/css/bootstrap.min.css', to: 'bootstrap.min.css' }];

await mkdir('public/vendor', { recursive: true });
const lines = ['# Vendored assets', '', 'Generated by `npm run vendor`. Do not edit by hand.', '', '| File | Package | Version | SHA-256 |', '|---|---|---|---|'];
for (const { pkg, from, to } of assets) {
  await copyFile(`node_modules/${pkg}/${from}`, `public/vendor/${to}`);
  const { version } = JSON.parse(await readFile(`node_modules/${pkg}/package.json`, 'utf8'));
  const hash = createHash('sha256').update(await readFile(`public/vendor/${to}`)).digest('hex');
  lines.push(`| \`${to}\` | \`${pkg}\` | ${version} | \`${hash}\` |`);
}
await writeFile('public/vendor/README.md', lines.join('\n') + '\n');
console.log(lines.slice(4).join('\n'));
